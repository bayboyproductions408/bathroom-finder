/* Creates the Android upload key.
     node tools/make-keystore.js

   This key signs the .aab you upload to Google Play. Keep it: with Play App
   Signing you can ask Google to reset a lost upload key, but it is a support
   round-trip you do not want mid-launch.

   The password is generated here and written to android/keystore.properties,
   which is git-ignored. If you would rather choose the password yourself, run
   keytool by hand — the command it uses is printed below.                   */
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
/* find keytool: an explicit JAVA_HOME wins, then the JDK sitting in dev-tools,
   then whatever is on PATH */
const findKeytool = () => {
  const fsx = require('fs'), px = require('path');
  if (process.env.JAVA_HOME){
    const c = px.join(process.env.JAVA_HOME, 'bin', 'keytool.exe');
    if (fsx.existsSync(c)) return c;
  }
  const base = 'C:/Dom/Claude/dev-tools/jdk17';
  if (fsx.existsSync(base)) for (const d of fsx.readdirSync(base)){
    const c = px.join(base, d, 'bin', 'keytool.exe');
    if (fsx.existsSync(c)) return c;
  }
  return 'keytool';
};
const KEYTOOL = findKeytool();
const STORE = path.join(ROOT, 'android', 'upload-keystore.jks');
const PROPS = path.join(ROOT, 'android', 'keystore.properties');
const ALIAS = 'bathroomfinder-upload';

if (fs.existsSync(STORE)){
  console.error(`\n${STORE} already exists. Refusing to overwrite it — replacing a`);
  console.error(`signing key you have already published with is not recoverable.`);
  console.error(`Delete it deliberately if you really mean to start over.\n`);
  process.exit(1);
}
if (!fs.existsSync(KEYTOOL)){
  console.error(`\nkeytool not found at ${KEYTOOL}. Point this script at your JDK.\n`);
  process.exit(1);
}

const password = crypto.randomBytes(24).toString('base64url');
const args = ['-genkeypair', '-v',
  '-keystore', STORE, '-alias', ALIAS,
  '-keyalg', 'RSA', '-keysize', '4096', '-validity', '10000',
  '-storepass', password, '-keypass', password,
  '-dname', 'CN=Bathroom Finder, OU=Mobile, O=Bathroom Finder, C=US'];

try { execFileSync(KEYTOOL, args, {stdio:'pipe'}); }
catch(err){
  console.error('keytool failed:', String(err.stderr || err.message));
  process.exit(1);
}

fs.writeFileSync(PROPS,
`# Generated by tools/make-keystore.js — keep this file private, never commit it.
# Losing it means you cannot ship an update signed with the same upload key.
storeFile=upload-keystore.jks
storePassword=${password}
keyAlias=${ALIAS}
keyPassword=${password}
`);

let fingerprint = '(run tools/make-assetlinks.js to read it)';
try {
  const out = execFileSync(KEYTOOL, ['-list','-v','-keystore',STORE,'-alias',ALIAS,'-storepass',password], {encoding:'utf8'});
  const m = out.match(/SHA256:\s*([A-F0-9:]+)/i);
  if (m) fingerprint = m[1];
} catch(e){}

console.log(`\nCreated the upload key.`);
console.log(`  keystore     android/upload-keystore.jks`);
console.log(`  credentials  android/keystore.properties  (git-ignored — back it up somewhere safe)`);
console.log(`  SHA-256      ${fingerprint}`);
console.log(`\nNext:  node tools/make-assetlinks.js\n`);
